-- ============================================================
-- contacts
-- ============================================================
create table if not exists public.contacts (
  id          uuid primary key default gen_random_uuid(),
  first_name  text not null,
  last_name   text not null,
  email       text not null unique,
  phone       text not null default '',
  color_index integer generated by default as identity,
  created_at  timestamptz not null default now()
);

comment on column public.contacts.color_index is
  'Auto-assigned, sequential. Used client-side on a golden-angle hue wheel to pick each contact''s avatar color.';

-- ============================================================
-- tasks
-- ============================================================
create table if not exists public.tasks (
  id          uuid primary key default gen_random_uuid(),
  title       text not null,
  description text,
  due_date    date,
  priority    text not null check (priority in ('urgent', 'medium', 'low')),
  status      text not null default 'todo'
              check (status in ('todo', 'in_progress', 'await_feedback', 'done')),
  category    text check (category in ('user_story', 'technical_task')),
  contact_ids uuid[],
  position    integer,
  created_at  timestamptz not null default now()
);

comment on column public.tasks.contact_ids is
  'IDs of assigned contacts.contacts. Not a DB foreign key (Postgres can''t FK into an array) — enforced app-side only.';
comment on column public.tasks.position is
  'Sort order within a status column on the board (drag-and-drop).';

create index if not exists tasks_status_idx on public.tasks (status);

-- ============================================================
-- subtasks
-- ============================================================
create table if not exists public.subtasks (
  id         uuid primary key default gen_random_uuid(),
  task_id    uuid not null references public.tasks (id) on delete cascade,
  title      text not null,
  done       boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists subtasks_task_id_idx on public.subtasks (task_id);

-- ============================================================
-- Row Level Security
-- The app is a shared team board (no per-row ownership), so any signed-in
-- user gets full read/write access to all three tables. Nothing is exposed
-- to anonymous (logged-out) requests.
-- ============================================================
alter table public.contacts enable row level security;
alter table public.tasks    enable row level security;
alter table public.subtasks enable row level security;

create policy "authenticated full access" on public.contacts
  for all to authenticated using (true) with check (true);

create policy "authenticated full access" on public.tasks
  for all to authenticated using (true) with check (true);

create policy "authenticated full access" on public.subtasks
  for all to authenticated using (true) with check (true);

